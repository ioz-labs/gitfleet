#!/usr/bin/env bash
# Build a native Arch Linux / pacman package (.pkg.tar.zst) and matching
# pacman repository database files (.db and .files) for GitFleet.
#
# Works on any Linux host (including Ubuntu 24.04 x86_64/arm64 CI runners)
# with: libarchive-tools (bsdtar), zstd, fakeroot, gzip, pacman-package-manager.

set -euo pipefail

usage() {
  cat <<'EOF'
Usage: build-pacman-pkg.sh \
  --version <ver> \
  --arch <x86_64|aarch64> \
  --binary <path> \
  --desktop <path> \
  --icon <path> \
  --license <path> \
  --readme <path> \
  --out-dir <dir> \
  [--pkgrel <num>]
EOF
}

VERSION=""
PKGREL="1"
ARCH=""
BINARY=""
DESKTOP=""
ICON=""
LICENSE_FILE=""
README_FILE=""
OUT_DIR=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --version)  VERSION="${2:?missing value for --version}"; shift 2 ;;
    --pkgrel)   PKGREL="${2:?missing value for --pkgrel}"; shift 2 ;;
    --arch)     ARCH="${2:?missing value for --arch}"; shift 2 ;;
    --binary)   BINARY="${2:?missing value for --binary}"; shift 2 ;;
    --desktop)  DESKTOP="${2:?missing value for --desktop}"; shift 2 ;;
    --icon)     ICON="${2:?missing value for --icon}"; shift 2 ;;
    --license)  LICENSE_FILE="${2:?missing value for --license}"; shift 2 ;;
    --readme)   README_FILE="${2:?missing value for --readme}"; shift 2 ;;
    --out-dir)  OUT_DIR="${2:?missing value for --out-dir}"; shift 2 ;;
    -h|--help)  usage; exit 0 ;;
    *)          echo "Unknown argument: $1" >&2; usage >&2; exit 1 ;;
  esac
done

for var_name in VERSION ARCH BINARY DESKTOP ICON LICENSE_FILE README_FILE OUT_DIR; do
  if [[ -z "${!var_name}" ]]; then
    echo "Error: missing required argument for ${var_name}" >&2
    usage >&2
    exit 1
  fi
done

case "$ARCH" in
  x86_64|aarch64) ;;
  *)
    echo "Error: unsupported Arch architecture '${ARCH}' (expected x86_64 or aarch64)" >&2
    exit 1
    ;;
esac

for f in "$BINARY" "$DESKTOP" "$ICON" "$LICENSE_FILE" "$README_FILE"; do
  if [[ ! -f "$f" ]]; then
    echo "Error: required input file not found: $f" >&2
    exit 1
  fi
done

for cmd in bsdtar zstd fakeroot gzip repo-add pacman; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "Error: required tool not found in PATH: $cmd" >&2
    exit 1
  fi
done

# Sanitize version into a valid pacman pkgver (strip leading 'v', replace '-' with '_')
PKGVER="${VERSION#v}"
PKGVER="${PKGVER//-/_}"
if [[ ! "$PKGVER" =~ ^[A-Za-z0-9._+]+$ ]]; then
  echo "Error: invalid pacman pkgver derived from '${VERSION}': '${PKGVER}'" >&2
  exit 1
fi
if [[ ! "$PKGREL" =~ ^[0-9]+(\.[0-9]+)?$ ]]; then
  echo "Error: invalid pkgrel '${PKGREL}'" >&2
  exit 1
fi

mkdir -p "$OUT_DIR"
OUT_DIR="$(cd "$OUT_DIR" && pwd)"

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

PKG_ROOT="${WORK_DIR}/pkg"
mkdir -p "$PKG_ROOT"

install -Dm755 "$BINARY"       "${PKG_ROOT}/usr/bin/gitfleet"
install -Dm644 "$DESKTOP"      "${PKG_ROOT}/usr/share/applications/gitfleet.desktop"
install -Dm644 "$ICON"         "${PKG_ROOT}/usr/share/icons/hicolor/512x512/apps/gitfleet.png"
install -Dm644 "$LICENSE_FILE" "${PKG_ROOT}/usr/share/licenses/gitfleet/LICENSE"
install -Dm644 "$README_FILE"  "${PKG_ROOT}/usr/share/doc/gitfleet/README.md"

INSTALLED_SIZE="$(find "$PKG_ROOT" -type f -exec cat {} + | wc -c | tr -d '[:space:]')"
BUILD_DATE="${SOURCE_DATE_EPOCH:-$(date -u +%s)}"

cat > "${PKG_ROOT}/.PKGINFO" <<EOF
# Generated by packaging/arch/build-pacman-pkg.sh
pkgname = gitfleet
pkgbase = gitfleet
pkgver = ${PKGVER}-${PKGREL}
pkgdesc = Open-source, 100% pure-Rust multi-repository Git desktop workspace manager
url = https://github.com/ioz-labs/gitfleet
builddate = ${BUILD_DATE}
packager = GitFleet Contributors <https://github.com/ioz-labs/gitfleet>
size = ${INSTALLED_SIZE}
arch = ${ARCH}
license = MIT
conflict = gitfleet-bin
conflict = gitfleet-git
depend = git
depend = glibc
depend = fontconfig
depend = libxkbcommon
depend = hicolor-icon-theme
optdepend = libxkbcommon-x11: X11 keyboard support
optdepend = wayland: Wayland display support
optdepend = vulkan-icd-loader: hardware-accelerated GPU rendering
optdepend = xdg-desktop-portal: native file chooser dialogs
EOF
chmod 644 "${PKG_ROOT}/.PKGINFO"

PKG_BASENAME="gitfleet-${PKGVER}-${PKGREL}-${ARCH}.pkg.tar.zst"
PKG_FILE="${OUT_DIR}/${PKG_BASENAME}"

# Run chown, .MTREE generation, and final archiving inside a single fakeroot
# session so root:root ownership (uid=0, gid=0) matches between .MTREE and tar.
fakeroot -- bash -euo pipefail -c '
  pkg_root="$1"
  pkg_file="$2"
  build_date="$3"

  cd "$pkg_root"
  chown -R 0:0 .
  find . -exec touch -h -d "@${build_date}" {} +

  list_package_files() {
    (
      export LC_COLLATE=C
      shopt -s dotglob globstar
      printf "%s\0" **/*
    )
  }

  list_package_files | LANG=C bsdtar -cnf - --format=mtree \
    --options="!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link" \
    --null --files-from - --exclude .MTREE | gzip -c -f -n > .MTREE
  chown 0:0 .MTREE
  touch -d "@${build_date}" .MTREE

  list_package_files | LANG=C bsdtar --no-fflags --no-read-sparse -cnf - \
    --null --files-from - | zstd -c -T0 -19 - > "$pkg_file"
' _ "$PKG_ROOT" "$PKG_FILE" "$BUILD_DATE"

# Build pacman sync database (.db and .files) for this architecture
REPO_NAME="gitfleet-${ARCH}"
REPO_WORK="${WORK_DIR}/repo"
mkdir -p "$REPO_WORK"
cp "$PKG_FILE" "${REPO_WORK}/${PKG_BASENAME}"

repo-add "${REPO_WORK}/${REPO_NAME}.db.tar.gz" "${REPO_WORK}/${PKG_BASENAME}"

# Materialize .db and .files as regular files (GitHub Releases does not store symlinks)
cp -L "${REPO_WORK}/${REPO_NAME}.db"    "${OUT_DIR}/${REPO_NAME}.db"
cp -L "${REPO_WORK}/${REPO_NAME}.files" "${OUT_DIR}/${REPO_NAME}.files"

# Verify built package and pacman repo database using real pacman/libalpm
VERIFY_DIR="${WORK_DIR}/pacman-verify"
mkdir -p "${VERIFY_DIR}/rootfs/var/lib/pacman" "${VERIFY_DIR}/cache"
cat > "${VERIFY_DIR}/pacman.conf" <<EOF
[options]
Architecture = ${ARCH}
RootDir = ${VERIFY_DIR}/rootfs
DBPath = ${VERIFY_DIR}/rootfs/var/lib/pacman
CacheDir = ${VERIFY_DIR}/cache
LogFile = ${VERIFY_DIR}/pacman.log
SigLevel = Never

[${REPO_NAME}]
SigLevel = Never
Server = file://${OUT_DIR}
EOF

echo "=== Verifying ${PKG_BASENAME} and pacman repo (${REPO_NAME}) ==="
fakeroot -- bash -euo pipefail -c '
  conf="$1"
  pkg_file="$2"
  pacman --config "$conf" --noconfirm -Sy
  pacman --config "$conf" -Qpi "$pkg_file"
  pacman --config "$conf" -Qpl "$pkg_file"
  pacman --config "$conf" -Si gitfleet
  pacman --config "$conf" --noconfirm -Sdd gitfleet
  pacman --config "$conf" -Qkk gitfleet
' _ "${VERIFY_DIR}/pacman.conf" "$PKG_FILE"

echo "Built Arch Linux package and pacman repo successfully:"
ls -lh "$PKG_FILE" "${OUT_DIR}/${REPO_NAME}.db" "${OUT_DIR}/${REPO_NAME}.files"
